def main(slug: str = "arcstore") -> None:
    history = store.load_history(slug)

    count = 0
    for line in ROWS.strip().splitlines():
        day, clicks, impressions, ctr, position = line.split()
        dt.date.fromisoformat(day)  # validate
        store.record_day(
            history,
            day,
            "gsc",
            {
                "clicks": int(clicks),
                "impressions": int(impressions),
                "ctr": float(ctr) / 100,
                "position": float(position),
            },
        )
        count += 1

    store.save_history(slug, history)
    print(f"Seeded {count} days of Search Console history for {slug}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "arcstore")
